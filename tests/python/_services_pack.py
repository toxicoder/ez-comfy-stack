def services_stamp_rows() -> tuple[tuple[str, str, tuple[str, ...], bool], ...]:
    """Return (rel, occupancy, handoff, enhance_off_identity) for STAMP_SPECS."""
    from _lab_ids import rel_id

    return tuple(
        (
            rel_id(spec.rel),
            spec.occupancy,
            (),
            spec.enhance_pin,
        )
        for spec in SERVICES
    )
