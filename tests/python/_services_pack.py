_W_LAND = (832, 480)
_W_PORT = (480, 832)
_W_LOOP = (768, 768)
_L_LAND = (1280, 704)
_L_PORT = (768, 1280)


@dataclass(frozen=True)
class ServiceSpec:
    """One services-pack graph.

    Attributes:
        rel: ``extra.lab_rel`` (``services/ecommerce/pdp-on-white``).
        kind: ``klein_single`` | ``wan_i2v`` | ``wan_loop`` | ``ltx_av``.
        group: Vertical folder / catalog section id.
        size: Width x height latent pixels.
        prefix: Primary SaveImage / VHS filename prefix.
        occupancy: ``klein`` | ``wan`` | ``ltx``.
        sample_catalog: Existing sample index id (reuse families only).
        title: One-line job for Notes and catalog.
        lock: Job-specific framing appended to the family identity.
        enhance_pin: True pins Prompt Enhance off.
        template: Klein ``hero``/``draft``, or a video source rel.
        identity: ``creator`` | ``product`` | ``food`` | ``desk`` | ``interior``.
        ltx_mode: ``i2v`` or ``t2v``.
        audio_hint: LTX world-SFX widget.
        portrait: True uses 9:16 Wan/LTX printers.
    """

    rel: str
    kind: str
    group: str
    size: tuple[int, int]
    prefix: str
    occupancy: str
    sample_catalog: str
    title: str
    lock: str
    enhance_pin: bool = False
    template: str = "hero"
    identity: str = "creator"
    ltx_mode: str = "i2v"
    audio_hint: str = "world SFX matching the shot, no score"
    portrait: bool = False


def _klein_template(width: int, height: int) -> str:
    """Return Klein printer id for a canvas.

    Arguments:
        width: Latent width.
        height: Latent height.
    Returns:
        ``draft`` or ``hero``.
    """
    if (width, height) in {_K_DRAFT, _K_45, _K_916}:
        return "draft"
    return "hero"


def _k(
    vertical: str,
    stem: str,
    size: tuple[int, int],
    prefix: str,
    title: str,
    lock: str,
    *,
    catalog: str = "klein_t2i",
    identity: str = "creator",
) -> ServiceSpec:
    """Klein single-plate spec."""
    width, height = size
    return ServiceSpec(
        rel=f"services/{vertical}/{stem}",
        kind="klein_single",
        group=vertical,
        size=size,
        prefix=prefix,
        occupancy="klein",
        sample_catalog=catalog,
        title=title,
        lock=lock,
        template=_klein_template(width, height),
        identity=identity,
    )


def _w(
    vertical: str,
    stem: str,
    size: tuple[int, int],
    prefix: str,
    title: str,
    lock: str,
    *,
    loop: bool = False,
) -> ServiceSpec:
    """Wan silent I2V or ping-pong loop."""
    width, height = size
    portrait = height > width
    return ServiceSpec(
        rel=f"services/{vertical}/{stem}",
        kind="wan_loop" if loop else "wan_i2v",
        group=vertical,
        size=size,
        prefix=prefix,
        occupancy="wan",
        sample_catalog="wan_loop" if loop else "wan_i2v",
        title=title,
        lock=lock,
        enhance_pin=True,
        portrait=portrait,
        template=(
            "motion/loops/gif-loop"
            if loop
            else (
                "motion/silent/shorts-still-5s"
                if portrait
                else "motion/silent/still-to-video-5s"
            )
        ),
    )


def _l(
    vertical: str,
    stem: str,
    size: tuple[int, int],
    prefix: str,
    title: str,
    lock: str,
    *,
    mode: str = "i2v",
    catalog: str | None = None,
    audio: str = "world SFX matching the shot, no score",
) -> ServiceSpec:
    """LTX AV clip."""
    width, height = size
    portrait = height > width
    if catalog is None:
        catalog = "ltx_broll" if mode == "t2v" else "ltx_i2v"
    src = (
        "motion/av/shorts-still-12s"
        if portrait
        else (
            "motion/av/text-to-video-12s"
            if mode == "t2v"
            else "motion/av/still-to-video-12s"
        )
    )
    return ServiceSpec(
        rel=f"services/{vertical}/{stem}",
        kind="ltx_av",
        group=vertical,
        size=size,
        prefix=prefix,
        occupancy="ltx",
        sample_catalog=catalog,
        title=title,
        lock=lock,
        ltx_mode=mode,
        audio_hint=audio,
        portrait=portrait,
        template=src,
    )


