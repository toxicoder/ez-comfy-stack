def test_appfilter_maps_by_component_and_package() -> None:
    with_activity = IconSpec(
        slug="with-activity",
        name="With Activity",
        package="com.sample.app",
        component=".MainActivity",
    )
    package_only = by_slug("phone-handset")
    assert package_only is not None, "the catalog carries package-only entries"
    assert package_only.component == "", "a launcher-name entry maps by package"
    text = appfilter_xml([with_activity, ENTRIES[0], package_only], "Demo Pack")
    assert "<!-- Demo Pack: generated by ez_icons -->" in text
    assert '<iconback img1="iconback" />' in text
    assert '<iconmask img1="iconmask" />' in text
    assert '<iconupon img1="iconupon" />' in text
    assert '<scale factor="1.0" />' in text
    assert 'component="ComponentInfo{com.sample.app/.MainActivity}"' in text
    assert f'package="{package_only.package}"' in text
    assert f'drawable="{package_only.drawable}"' in text
    assert "ComponentInfo{com.talkline.messenger" in text
    assert 'drawable="with_activity"' in text
    assert "icon_com.talkline.messenger" not in text


