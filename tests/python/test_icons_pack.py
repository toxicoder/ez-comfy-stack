def test_master_art_path_walks_every_suffix(tmp_path: Path) -> None:
    spec = by_slug("chat-bubble")
    assert spec is not None
    assert _master_path(spec, None) is None
    art = tmp_path / "art"
    art.mkdir()
    assert _master_path(spec, art) is None
    for suffix in (".png", ".webp", ".jpg"):
        (art / f"{spec.slug}{suffix}").write_bytes(b"placeholder")
        assert _master_path(spec, art) == str(art / f"{spec.slug}{suffix}")
        (art / f"{spec.slug}{suffix}").unlink()
    (art / "someone-else.png").write_bytes(b"placeholder")
    assert _master_path(spec, art) is None


def test_build_reports_a_broken_master_and_an_absent_art_dir(tmp_path: Path) -> None:
    art = tmp_path / "art"
    art.mkdir()
    (art / "chat-bubble.png").write_bytes(b"not a real master")
    with pytest.raises(RasterError):
        build_pack(ICON_CATALOG, tmp_path / "broken", only_slugs=["chat-bubble"], art_dir=art)
    result = build_pack(
        ICON_CATALOG, tmp_path / "plain", only_slugs=["chat-bubble"], art_dir=tmp_path / "absent"
    )
    payload = json.loads((tmp_path / "plain" / "manifest.json").read_text(encoding="utf-8"))
    assert payload["icons"][0]["master"] is None
    assert result.icon_count == 1


