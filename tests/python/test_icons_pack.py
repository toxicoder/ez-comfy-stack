def _dry_records(result: PackResult) -> list[IconLayers]:
    """Rebuild the layer records a dry run reported.

    Args:
        result: The dry-run result.

    Returns:
        Layer records, one per entry, in entry order.
    """
    records: list[IconLayers] = []
    for spec in ENTRIES:
        records.append(
            _dry_layers(spec, icon_layer_paths(spec.drawable, "drawable", False, "_themed"), None)
        )
    assert len(records) == result.icon_count
    return records


