def test_build_writes_every_asset(built: tuple[Path, PackResult]) -> None:
    out, result = built
    assert result.icon_count == len(ENTRIES)
    assert result.dry_run is False
    assert result.pack_name == "Demo Pack"
    assert result.pack_version == "2.3.4"
    assert result.files == tuple(sorted(result.files))
    assert result.total_bytes == sum(
        (out / name).stat().st_size for name in result.files
    )
    on_disk = sorted(
        str(path.relative_to(out)) for path in out.rglob("*") if path.is_file()
    )
    assert on_disk == list(result.files)
    for name, edge in ADAPTIVE_LADDER:
        for spec in ENTRIES:
            for suffix in ("_foreground", "_background", "_themed"):
                folder = out / "app/src/main/res" / f"drawable-{name}"
                assert png_shape(folder / f"{spec.drawable}{suffix}.png")[:2] == (edge, edge)
    for name, edge in LEGACY_LADDER:
        for spec in ENTRIES:
            folder = out / "app/src/main/res" / f"drawable-{name}"
            assert png_shape(folder / f"{spec.drawable}.png")[:2] == (edge, edge)


