#!/usr/bin/env python3
"""Regenerate the frontend Detail ladder table from custom_nodes/ez_quality.

Not imported by pytest (leading underscore). Canonical entry point:

  bazelisk run //tests:build_quality_js

which writes custom_nodes/ez_quality/js/ez_quality_presets.js in place. Pass
--check to fail instead of writing when the committed file has drifted from
presets.py:

  bazelisk test //tests:build_quality_js_check

Direct host use stays available: python3 tests/python/_build_quality_js.py

The generated file is the only Quality tier data the frontend reads. Editing
custom_nodes/ez_quality/js/ez_quality_presets.js by hand is a defect: rerun this
and let presets.py stay the definition.
"""

from __future__ import annotations

import json
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "custom_nodes"))

from ez_quality.presets import export_table  # noqa: E402

OUTPUT = REPO_ROOT / "custom_nodes" / "ez_quality" / "js" / "ez_quality_presets.js"

_HEADER = """/**
 * @file Detail ladder table for the EZQuality combo.
 * @generated by tests/python/_build_quality_js.py - do not edit by hand.
 *
 * Every number and filename here comes from
 * custom_nodes/ez_quality/presets.py, which is the single definition. Regenerate
 * with `bazelisk run //tests:build_quality_js` after touching presets.py.
 *
 * Shapes:
 *   EZ_QUALITY_CHOICES            the three rungs: draft, standard, final.
 *   EZ_QUALITY_DEFAULT            the rung every App opens on (standard).
 *   EZ_QUALITY_TABLE[family][rung] requested value per overlay field, null =
 *                                  leave the authored widget alone. standard is
 *                                  all-null on every family: it writes nothing.
 *   EZ_QUALITY_OWNED[family]      fields that family's rungs ever set; a change
 *                                  outside this list is what the caption reports
 *                                  as Edited.
 *   EZ_QUALITY_LABELS[family][rung] caption naming the swap, for the combo.
 *   EZ_QUALITY_TIERS[family]      the only rungs that family can honor; a family
 *                                  with an empty list ships no row at all.
 *   EZ_QUALITY_LICENSES[family]   the license word the caption must state.
 *   EZ_QUALITY_STACKS / _UNET_STACKS  human names for the caption.
 *   EZ_QUALITY_RUNG_LABELS        Draft / Standard / Final for the combo.
 *   EZ_QUALITY_FIELD_NAMES        overlay field -> widget name on the node.
 *   EZ_QUALITY_EDITED_PREFIX      prefix the caption carries after a hand edit.
 */
"""


def render() -> str:
    """Render the generated module body.

    Args:
        None.

    Returns:
        JavaScript source for ez_quality_presets.js.
    """
    table = export_table()
    blocks = []
    for key in (
        "choices",
        "default",
        "named",
        "families",
        "fields",
        "table",
        "owned",
        "labels",
        "tiers",
        "licenses",
        "stacks",
        "unet_stacks",
        "rung_labels",
        "field_names",
        "edited_prefix",
    ):
        const = "EZ_QUALITY_" + key.upper()
        body = json.dumps(table[key], indent=2, ensure_ascii=True, sort_keys=False)
        blocks.append(f"export const {const} = {body};\n")
    return _HEADER + "\n" + "\n".join(blocks)


def main(argv: list[str] | None = None) -> int:
    """Write the generated module, or verify it without writing.

    Args:
        argv: Argument list after the program name. ``--check`` switches to
            verify-only mode, used by //tests:build_quality_js_check.

    Returns:
        Process exit code. 1 in --check mode when the file on disk differs
        from what presets.py renders.
    """
    args = list(sys.argv[1:] if argv is None else argv)
    check = "--check" in args
    body = render()
    if check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != body:
            print(f"{OUTPUT.relative_to(REPO_ROOT)} is stale; "
                  "run: bazelisk run //tests:build_quality_js")
            return 1
        print(f"{OUTPUT.relative_to(REPO_ROOT)} matches presets.py")
        return 0
    OUTPUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
