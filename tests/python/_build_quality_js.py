#!/usr/bin/env python3
"""Regenerate the frontend Quality tier table from custom_nodes/ez_quality.

Not imported by pytest (leading underscore). Run from repo root:

  python3 tests/python/_build_quality_js.py

The generated file is the only Quality tier data the frontend reads. Editing
custom_nodes/ez_quality/js/ez_quality_presets.js by hand is a defect: rerun this
and let presets.py stay the definition.
"""

from __future__ import annotations

import json
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "custom_nodes"))

from ez_quality.presets import export_table  # noqa: E402

OUTPUT = REPO_ROOT / "custom_nodes" / "ez_quality" / "js" / "ez_quality_presets.js"

_HEADER = """/**
 * @file Quality tier table for the EZQuality combo.
 * @generated by tests/python/_build_quality_js.py - do not edit by hand.
 *
 * Every number and filename here comes from
 * custom_nodes/ez_quality/presets.py, which is the single definition. Regenerate
 * with `python3 tests/python/_build_quality_js.py` after touching presets.py.
 *
 * Shapes:
 *   EZ_QUALITY_TABLE[family][tier]  requested value per overlay field, null =
 *                                   leave the authored widget alone.
 *   EZ_QUALITY_OWNED[family]        fields that family's tiers ever set; a
 *                                   change outside this list keeps the level.
 *   EZ_QUALITY_LABELS[family][tier] caption naming the swap, for the combo.
 */
"""


def render() -> str:
    """Render the generated module body.

    Args:
        None.

    Returns:
        JavaScript source for ez_quality_presets.js.
    """
    table = export_table()
    blocks = []
    for key in ("choices", "named", "families", "fields", "table", "owned", "labels"):
        const = "EZ_QUALITY_" + key.upper()
        body = json.dumps(table[key], indent=2, ensure_ascii=True, sort_keys=False)
        blocks.append(f"export const {const} = {body};\n")
    blocks.append(f"export const EZ_QUALITY_CUSTOM = {json.dumps(table['custom'])};\n")
    blocks.append(f"export const EZ_QUALITY_LAB = {json.dumps(table['lab'])};\n")
    return _HEADER + "\n" + "\n".join(blocks)


def main() -> int:
    """Write the generated module.

    Args:
        None.

    Returns:
        Process exit code.
    """
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
